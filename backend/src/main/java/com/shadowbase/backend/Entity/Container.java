package com.shadowbase.backend.Entity;

import java.time.LocalDateTime;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/**
 * JPA Entity representing an isolated database container running in Docker.
 * Persists runtime connection details, dynamic port bindings, credentials, and lifecycle status.
 */
@Entity
@Table(name = "containers")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
@ToString(exclude = {"sandbox", "dataSource"})
@EqualsAndHashCode(exclude = {"sandbox", "dataSource"})
public class Container {

    /**
     * Unique Docker container ID generated by the Docker engine.
     */
    @Id
    private String id;

    /**
     * The parent Sandbox environment that this container belongs to.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "sandbox_id", referencedColumnName = "id")
    private Sandbox sandbox;

    /**
     * Docker image used (e.g. "postgres:16-alpine", "mysql:8.4").
     */
    @Column(name = "image_name")
    private String imageName;

    /**
     * Host address to reach the container (typically localhost or dockerHostIpAddress).
     */
    private String host;

    /**
     * Dynamically mapped host port forwarded to the container's standard internal port.
     */
    private Integer port;

    /**
     * Complete JDBC connection URL for direct database client connections.
     */
    @Column(name = "jdbc_url", length = 1024)
    private String jdbcUrl;

    /**
     * Database administrator username.
     */
    private String username;

    /**
     * Database password. Stored internally, never exposed via API response DTOs.
     */
    private String password;

    /**
     * Reference to external secret/credential store if configured.
     */
    @Column(name = "credential_reference")
    private String credentialReference;

    /**
     * Optional source database reference associated with this container.
     * Each container hosts exactly one database, and a DataSource is linked
     * exclusively to only this container (completely independent of Sandbox).
     */
    @OneToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "data_source_id", referencedColumnName = "id", unique = true)
    private DataSource dataSource;

    /**
     * Logical name of the database created inside the container.
     */
    @Column(name = "database_name")
    private String databaseName;

    /**
     * Supported database type: MYSQL or POSTGRESQL.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "database_type")
    private DatabaseType databaseType;

    /**
     * Current lifecycle status of the container.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false)
    private ContainerStatus status;

    /**
     * Schema initialization status for the single database running inside this container.
     * Each container hosts exactly one database and has only one schema.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "schema_status")
    @Builder.Default
    private SchemaStatus schemaStatus = SchemaStatus.NOT_INITIALIZED;

    /**
     * Timestamp when this container record was created.
     */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * Timestamp when this container record was last updated.
     */
    @UpdateTimestamp
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    /**
     * Timestamp when this container should automatically expire and be decommissioned.
     */
    @Column(name = "expires_at", nullable = true)
    private LocalDateTime expiresAt;

    /**
     * Timestamp when this container was stopped.
     */
    @Column(name = "stopped_at", nullable = true)
    private LocalDateTime stoppedAt;

    /**
     * Supported container database engines.
     */
    public enum DatabaseType {
        MYSQL, POSTGRESQL
    }

    /**
     * Independent lifecycle statuses for containers.
     */
    public enum ContainerStatus {
        CREATING, STARTING, RUNNING, UNHEALTHY, STOPPING, STOPPED, FAILED, REMOVED
    }
}
