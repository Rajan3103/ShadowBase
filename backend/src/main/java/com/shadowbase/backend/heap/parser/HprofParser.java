package com.shadowbase.backend.heap.parser;

import java.io.BufferedInputStream;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.DataInputStream;
import java.io.EOFException;
import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import org.springframework.stereotype.Component;

import com.shadowbase.backend.heap.model.GCRoot;
import com.shadowbase.backend.heap.model.GCRootType;
import com.shadowbase.backend.heap.model.HeapClass;
import com.shadowbase.backend.heap.model.HeapField;
import com.shadowbase.backend.heap.model.HeapObject;
import com.shadowbase.backend.heap.model.HeapSnapshot;

import lombok.extern.slf4j.Slf4j;

/**
 * High-performance binary HPROF parser conforming to the Java HPROF 1.0.1/1.0.2 specification.
 * <p>
 * Parses binary heap dumps generated by HotSpot JVM, jcmd, jmap, or Android heap dumps,
 * populating a fully queryable {@link HeapSnapshot}.
 */
@Slf4j
@Component
public class HprofParser {

    private static final int TAG_STRING = 0x01;
    private static final int TAG_LOAD_CLASS = 0x02;
    private static final int TAG_HEAP_DUMP = 0x0C;
    private static final int TAG_HEAP_DUMP_SEGMENT = 0x1C;
    private static final int TAG_HEAP_DUMP_END = 0x2C;

    // Heap dump sub-tags
    private static final int SUB_ROOT_UNKNOWN = 0xFF;
    private static final int SUB_ROOT_JNI_GLOBAL = 0x01;
    private static final int SUB_ROOT_JNI_LOCAL = 0x02;
    private static final int SUB_ROOT_JAVA_FRAME = 0x03;
    private static final int SUB_ROOT_NATIVE_STACK = 0x04;
    private static final int SUB_ROOT_STICKY_CLASS = 0x05;
    private static final int SUB_ROOT_THREAD_BLOCK = 0x06;
    private static final int SUB_ROOT_MONITOR_USED = 0x07;
    private static final int SUB_ROOT_THREAD_OBJECT = 0x08;
    private static final int SUB_CLASS_DUMP = 0x20;
    private static final int SUB_INSTANCE_DUMP = 0x21;
    private static final int SUB_OBJECT_ARRAY_DUMP = 0x22;
    private static final int SUB_PRIMITIVE_ARRAY_DUMP = 0x23;

    public HeapSnapshot parse(File file) throws IOException {
        try (InputStream fis = new BufferedInputStream(new FileInputStream(file))) {
            return parse(fis);
        }
    }

    public HeapSnapshot parse(byte[] bytes) throws IOException {
        try (InputStream bis = new ByteArrayInputStream(bytes)) {
            return parse(bis);
        }
    }

    public HeapSnapshot parse(InputStream inputStream) throws IOException {
        DataInputStream in = new DataInputStream(new BufferedInputStream(inputStream));
        HeapSnapshot snapshot = new HeapSnapshot();
        snapshot.setSnapshotId(UUID.randomUUID().toString());

        // 1. Read header null-terminated string
        String headerVersion = readNullTerminatedString(in);
        if (!headerVersion.startsWith("JAVA PROFILE")) {
            throw new HprofParseException("Unsupported or invalid HPROF header: " + headerVersion);
        }
        snapshot.setHeaderVersion(headerVersion);

        // 2. Read identifier size (4 or 8 bytes)
        int idSize = in.readInt();
        if (idSize != 4 && idSize != 8) {
            throw new HprofParseException("Invalid identifier size: " + idSize + " (expected 4 or 8)");
        }
        snapshot.setIdSize(idSize);

        // 3. Read timestamp (high + low u4)
        long timestamp = in.readLong();
        snapshot.setDumpTimestamp(timestamp);

        log.debug("Parsing HPROF dump version='{}', idSize={}, timestamp={}", headerVersion, idSize, timestamp);

        Map<Long, String> strings = new HashMap<>();
        Map<Long, String> classNamesByObjectId = new HashMap<>();
        List<InstanceDumpRecord> pendingInstances = new ArrayList<>();

        // 4. Parse top-level records
        try {
            while (true) {
                int tag;
                try {
                    tag = in.readUnsignedByte();
                } catch (EOFException e) {
                    break;
                }

                int time = in.readInt();
                long length = in.readInt() & 0xFFFFFFFFL;

                switch (tag) {
                    case TAG_STRING -> {
                        long stringId = readId(in, idSize);
                        int stringBytesLen = (int) (length - idSize);
                        byte[] strBytes = new byte[stringBytesLen];
                        in.readFully(strBytes);
                        String strVal = new String(strBytes, StandardCharsets.UTF_8);
                        strings.put(stringId, strVal);
                    }
                    case TAG_LOAD_CLASS -> {
                        in.readInt(); // class serial
                        long classObjectId = readId(in, idSize);
                        in.readInt(); // stack trace serial
                        long classNameStringId = readId(in, idSize);
                        String className = strings.getOrDefault(classNameStringId, "Class_" + classObjectId);
                        className = className.replace('/', '.');
                        classNamesByObjectId.put(classObjectId, className);
                    }
                    case TAG_HEAP_DUMP, TAG_HEAP_DUMP_SEGMENT -> {
                        parseHeapDumpSegment(in, length, idSize, snapshot, strings, classNamesByObjectId, pendingInstances);
                    }
                    case TAG_HEAP_DUMP_END -> {
                        // End of heap dump segments
                    }
                    default -> {
                        // Skip unused records
                        skipFully(in, length);
                    }
                }
            }
        } catch (EOFException e) {
            log.debug("Reached end of HPROF stream");
        }

        // 5. Resolve instance fields & references for pending instances
        resolvePendingInstances(snapshot, pendingInstances, idSize, classNamesByObjectId);

        // 6. Enrich class names and mark GC roots on all objects
        for (GCRoot root : snapshot.getGcRoots()) {
            HeapObject obj = snapshot.getObject(root.getObjectId());
            if (obj != null) {
                obj.setGcRoot(true);
                obj.setRootType(root.getType());
            }
        }

        for (HeapObject obj : snapshot.getObjects().values()) {
            if (obj.getClassName() == null || obj.getClassName().isEmpty()) {
                String cName = classNamesByObjectId.get(obj.getClassId());
                obj.setClassName(cName != null ? cName : "Object_0x" + Long.toHexString(obj.getClassId()));
            }
        }

        // 7. Index incoming reference graph
        snapshot.buildIncomingReferences();

        log.info("HPROF parsed successfully: {} objects, {} classes, {} GC roots, total size: {} bytes",
                snapshot.getObjects().size(), snapshot.getClasses().size(), snapshot.getGcRoots().size(),
                snapshot.getTotalHeapSize());

        return snapshot;
    }

    private void parseHeapDumpSegment(
            DataInputStream in,
            long segmentLength,
            int idSize,
            HeapSnapshot snapshot,
            Map<Long, String> strings,
            Map<Long, String> classNamesByObjectId,
            List<InstanceDumpRecord> pendingInstances) throws IOException {

        long bytesRead = 0;
        while (bytesRead < segmentLength) {
            int subTag = in.readUnsignedByte();
            bytesRead += 1;

            switch (subTag) {
                // GC Roots
                case SUB_ROOT_UNKNOWN, SUB_ROOT_STICKY_CLASS, SUB_ROOT_MONITOR_USED -> {
                    long objectId = readId(in, idSize);
                    bytesRead += idSize;
                    snapshot.addGCRoot(GCRoot.builder()
                            .objectId(objectId)
                            .type(GCRootType.fromHprofTag(subTag))
                            .build());
                }
                case SUB_ROOT_JNI_GLOBAL -> {
                    long objectId = readId(in, idSize);
                    readId(in, idSize); // JNI global ref ID
                    bytesRead += (idSize * 2);
                    snapshot.addGCRoot(GCRoot.builder()
                            .objectId(objectId)
                            .type(GCRootType.JNI_GLOBAL)
                            .build());
                }
                case SUB_ROOT_JNI_LOCAL, SUB_ROOT_JAVA_FRAME -> {
                    long objectId = readId(in, idSize);
                    int threadSerial = in.readInt();
                    int frameNumber = in.readInt();
                    bytesRead += (idSize + 8);
                    snapshot.addGCRoot(GCRoot.builder()
                            .objectId(objectId)
                            .type(GCRootType.fromHprofTag(subTag))
                            .context("thread=" + threadSerial + ", frame=" + frameNumber)
                            .build());
                }
                case SUB_ROOT_NATIVE_STACK, SUB_ROOT_THREAD_BLOCK -> {
                    long objectId = readId(in, idSize);
                    int threadSerial = in.readInt();
                    bytesRead += (idSize + 4);
                    snapshot.addGCRoot(GCRoot.builder()
                            .objectId(objectId)
                            .type(GCRootType.fromHprofTag(subTag))
                            .context("thread=" + threadSerial)
                            .build());
                }
                case SUB_ROOT_THREAD_OBJECT -> {
                    long objectId = readId(in, idSize);
                    int threadSeq = in.readInt();
                    int stackSeq = in.readInt();
                    bytesRead += (idSize + 8);
                    snapshot.addGCRoot(GCRoot.builder()
                            .objectId(objectId)
                            .type(GCRootType.THREAD_OBJECT)
                            .context("threadSeq=" + threadSeq)
                            .build());
                }

                // Class Dump
                case SUB_CLASS_DUMP -> {
                    long classObjectId = readId(in, idSize);
                    in.readInt(); // stack trace
                    long superclassObjectId = readId(in, idSize);
                    long classLoaderObjectId = readId(in, idSize);
                    readId(in, idSize); // signers
                    readId(in, idSize); // protection domain
                    readId(in, idSize); // reserved
                    readId(in, idSize); // reserved
                    int instanceSize = in.readInt();
                    bytesRead += (idSize * 7 + 8);

                    HeapClass heapClass = HeapClass.builder()
                            .classId(classObjectId)
                            .name(classNamesByObjectId.get(classObjectId))
                            .superclassId(superclassObjectId)
                            .classLoaderId(classLoaderObjectId)
                            .instanceSize(instanceSize)
                            .build();

                    // Constant pool
                    int cpCount = in.readUnsignedShort();
                    bytesRead += 2;
                    for (int i = 0; i < cpCount; i++) {
                        in.readUnsignedShort(); // index
                        int type = in.readUnsignedByte();
                        int size = HeapField.getTypeSize(type, idSize);
                        skipFully(in, size);
                        bytesRead += (3 + size);
                    }

                    // Static fields
                    int staticCount = in.readUnsignedShort();
                    bytesRead += 2;
                    for (int i = 0; i < staticCount; i++) {
                        readId(in, idSize); // field name id
                        int type = in.readUnsignedByte();
                        bytesRead += (idSize + 1);
                        if (type == 2) { // Object reference
                            long refId = readId(in, idSize);
                            bytesRead += idSize;
                            heapClass.addStaticReference(refId);
                        } else {
                            int size = HeapField.getTypeSize(type, idSize);
                            skipFully(in, size);
                            bytesRead += size;
                        }
                    }

                    // Instance fields
                    int ifCount = in.readUnsignedShort();
                    bytesRead += 2;
                    for (int i = 0; i < ifCount; i++) {
                        long nameId = readId(in, idSize);
                        int type = in.readUnsignedByte();
                        bytesRead += (idSize + 1);
                        String fName = strings.getOrDefault(nameId, "field_" + i);
                        heapClass.addInstanceField(HeapField.builder()
                                .name(fName)
                                .typeCode(type)
                                .typeName(HeapField.getTypeNameFromCode(type))
                                .reference(type == 2)
                                .build());
                    }

                    snapshot.addClass(heapClass);

                    // Add class itself as a heap object
                    HeapObject classObj = HeapObject.builder()
                            .objectId(classObjectId)
                            .className("java.lang.Class")
                            .shallowSize(instanceSize > 0 ? instanceSize : (idSize * 4L + 16))
                            .outReferences(new ArrayList<>(heapClass.getStaticReferences()))
                            .build();
                    snapshot.addObject(classObj);
                }

                // Instance Dump
                case SUB_INSTANCE_DUMP -> {
                    long objectId = readId(in, idSize);
                    in.readInt(); // stack trace
                    long classObjectId = readId(in, idSize);
                    int numBytes = in.readInt();
                    byte[] data = new byte[numBytes];
                    in.readFully(data);
                    bytesRead += (idSize * 2 + 8 + numBytes);

                    pendingInstances.add(new InstanceDumpRecord(objectId, classObjectId, data));
                }

                // Object Array Dump
                case SUB_OBJECT_ARRAY_DUMP -> {
                    long objectId = readId(in, idSize);
                    in.readInt(); // stack trace
                    int numElements = in.readInt();
                    long elementClassObjectId = readId(in, idSize);
                    bytesRead += (idSize * 2 + 8);

                    List<Long> refs = new ArrayList<>(numElements);
                    for (int i = 0; i < numElements; i++) {
                        long refId = readId(in, idSize);
                        if (refId != 0) {
                            refs.add(refId);
                        }
                    }
                    bytesRead += ((long) numElements * idSize);

                    String elemName = classNamesByObjectId.get(elementClassObjectId);
                    String arrayClassName = (elemName != null ? elemName : "Object") + "[]";
                    long shallowSize = 16L + 4L + 4L + ((long) numElements * idSize);

                    HeapObject arrayObj = HeapObject.builder()
                            .objectId(objectId)
                            .classId(elementClassObjectId)
                            .className(arrayClassName)
                            .shallowSize(shallowSize)
                            .array(true)
                            .arrayLength(numElements)
                            .primitiveArray(false)
                            .outReferences(refs)
                            .build();
                    snapshot.addObject(arrayObj);
                }

                // Primitive Array Dump
                case SUB_PRIMITIVE_ARRAY_DUMP -> {
                    long objectId = readId(in, idSize);
                    in.readInt(); // stack trace
                    int numElements = in.readInt();
                    int elemType = in.readUnsignedByte();
                    bytesRead += (idSize + 9);

                    int elemSize = HeapField.getTypeSize(elemType, idSize);
                    long totalArrayBytes = (long) numElements * elemSize;
                    skipFully(in, totalArrayBytes);
                    bytesRead += totalArrayBytes;

                    String primName = HeapField.getTypeNameFromCode(elemType) + "[]";
                    long shallowSize = 16L + 4L + 4L + totalArrayBytes;

                    HeapObject primArrayObj = HeapObject.builder()
                            .objectId(objectId)
                            .className(primName)
                            .shallowSize(shallowSize)
                            .array(true)
                            .arrayLength(numElements)
                            .primitiveArray(true)
                            .build();
                    snapshot.addObject(primArrayObj);
                }

                default -> {
                    log.warn("Unknown sub-tag 0x{} in heap dump segment at position {}",
                            Integer.toHexString(subTag), bytesRead);
                    return;
                }
            }
        }
    }

    private void resolvePendingInstances(
            HeapSnapshot snapshot,
            List<InstanceDumpRecord> pendingInstances,
            int idSize,
            Map<Long, String> classNamesByObjectId) {

        for (InstanceDumpRecord record : pendingInstances) {
            HeapClass clazz = snapshot.getClass(record.classObjectId);
            List<Long> refs = new ArrayList<>();
            long shallowSize = clazz != null && clazz.getInstanceSize() > 0
                    ? clazz.getInstanceSize()
                    : (16L + record.data.length);

            // Collect all instance fields by walking up class inheritance hierarchy
            List<HeapField> allFields = collectHierarchyFields(snapshot, record.classObjectId);

            if (!allFields.isEmpty()) {
                DataInputStream dis = new DataInputStream(new ByteArrayInputStream(record.data));
                try {
                    for (HeapField field : allFields) {
                        if (dis.available() <= 0) {
                            break;
                        }
                        if (field.isReference()) {
                            long refId = readId(dis, idSize);
                            if (refId != 0 && refId != record.objectId) {
                                refs.add(refId);
                            }
                        } else {
                            int size = HeapField.getTypeSize(field.getTypeCode(), idSize);
                            int skipped = dis.skipBytes(size);
                            if (skipped < size) {
                                break;
                            }
                        }
                    }
                } catch (IOException e) {
                    log.debug("Error parsing instance fields for object 0x{}", Long.toHexString(record.objectId));
                }
            } else {
                // Fallback heuristic: scan raw bytes for non-zero reference pointers
                DataInputStream dis = new DataInputStream(new ByteArrayInputStream(record.data));
                try {
                    while (dis.available() >= idSize) {
                        long refId = readId(dis, idSize);
                        if (refId != 0 && refId != record.objectId) {
                            refs.add(refId);
                        }
                    }
                } catch (IOException ignored) {
                }
            }

            String cName = classNamesByObjectId.get(record.classObjectId);
            HeapObject obj = HeapObject.builder()
                    .objectId(record.objectId)
                    .classId(record.classObjectId)
                    .className(cName != null ? cName : "Object")
                    .shallowSize(shallowSize)
                    .outReferences(refs)
                    .build();

            snapshot.addObject(obj);
        }
    }

    private List<HeapField> collectHierarchyFields(HeapSnapshot snapshot, long classId) {
        List<HeapField> fields = new ArrayList<>();
        long currentClassId = classId;
        // Collect from superclass to subclass
        List<HeapClass> hierarchy = new ArrayList<>();
        while (currentClassId != 0) {
            HeapClass clazz = snapshot.getClass(currentClassId);
            if (clazz == null) {
                break;
            }
            hierarchy.add(0, clazz); // add to front so superclass is first
            currentClassId = clazz.getSuperclassId();
        }
        for (HeapClass c : hierarchy) {
            if (c.getInstanceFields() != null) {
                fields.addAll(c.getInstanceFields());
            }
        }
        return fields;
    }

    private long readId(DataInputStream in, int idSize) throws IOException {
        if (idSize == 4) {
            return in.readInt() & 0xFFFFFFFFL;
        } else {
            return in.readLong();
        }
    }

    private String readNullTerminatedString(DataInputStream in) throws IOException {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        int b;
        while ((b = in.read()) != 0 && b != -1) {
            baos.write(b);
        }
        return baos.toString(StandardCharsets.UTF_8);
    }

    private void skipFully(DataInputStream in, long bytes) throws IOException {
        long remaining = bytes;
        while (remaining > 0) {
            long skipped = in.skip(remaining);
            if (skipped <= 0) {
                if (in.read() == -1) {
                    throw new EOFException("Unexpected EOF while skipping " + remaining + " bytes");
                }
                remaining--;
            } else {
                remaining -= skipped;
            }
        }
    }

    private record InstanceDumpRecord(long objectId, long classObjectId, byte[] data) {}
}
